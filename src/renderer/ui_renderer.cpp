void UIRenderer::initFontTexture() {
    // Construct 128x128 font texture atlas (16 cols x 6 rows of 8x16 characters)
    std::vector<unsigned char> pixels(128 * 128, 0);

    for (int idx = 0; idx < 95; idx++) {
        int col = idx % 16;
        int row = idx / 16;
        int startX = col * 8;
        int startY = row * 16;

        for (int y = 0; y < 16; y++) {
            unsigned char rowByte = font8x16_data[idx][y];
            for (int x = 0; x < 8; x++) {
                if (rowByte & (1 << (7 - x))) {
                    int pixelX = startX + x;
                    int pixelY = startY + y;
                    pixels[pixelY * 128 + pixelX] = 255;
                }
            }
        }
    }

    glGenTextures(1, &m_fontTexture);
    glBindTexture(GL_TEXTURE_2D, m_fontTexture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RED, 128, 128, 0, GL_RED, GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
}

bool UIRenderer::initialize() {
    GLuint vs = glCreateShader(GL_VERTEX_SHADER);
    glShaderSource(vs, 1, &uiVertexShaderSource, nullptr);
    glCompileShader(vs);

    GLuint fs = glCreateShader(GL_FRAGMENT_SHADER);
    glShaderSource(fs, 1, &uiFragmentShaderSource, nullptr);
    glCompileShader(fs);

    m_shaderProgram = glCreateProgram();
    glAttachShader(m_shaderProgram, vs);
    glAttachShader(m_shaderProgram, fs);
    glLinkProgram(m_shaderProgram);

    glDeleteShader(vs);
    glDeleteShader(fs);

    m_locOrtho = glGetUniformLocation(m_shaderProgram, "uOrthoProjection");
    m_locColor = glGetUniformLocation(m_shaderProgram, "uColor");
    m_locAlpha = glGetUniformLocation(m_shaderProgram, "uAlpha");
    m_locUseTexture = glGetUniformLocation(m_shaderProgram, "uUseTexture");

    glGenVertexArrays(1, &m_vao);
    glGenBuffers(1, &m_vbo);

    glBindVertexArray(m_vao);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
    glBufferData(GL_ARRAY_BUFFER, sizeof(float) * 24, nullptr, GL_DYNAMIC_DRAW);

    glEnableVertexAttribArray(0); // Pos
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);
    glEnableVertexAttribArray(1); // TexCoord
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));

    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindVertexArray(0);

    initFontTexture();
    m_initialized = true;
    return true;
}

void UIRenderer::shutdown() {
    if (m_initialized) {
        if (m_shaderProgram) glDeleteProgram(m_shaderProgram);
        if (m_fontTexture) glDeleteTextures(1, &m_fontTexture);
        if (m_vao) glDeleteVertexArrays(1, &m_vao);
        if (m_vbo) glDeleteBuffers(1, &m_vbo);
        m_initialized = false;
    }
}

void UIRenderer::begin2D(int windowWidth, int windowHeight) {
    if (!m_initialized) return;

    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glUseProgram(m_shaderProgram);

    Mat4 ortho = Mat4::ortho(0.0f, static_cast<float>(windowWidth), static_cast<float>(windowHeight), 0.0f, -1.0f, 1.0f);
    glUniformMatrix4fv(m_locOrtho, 1, GL_FALSE, ortho.ptr());
}

void UIRenderer::end2D() {
    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);
}

void UIRenderer::drawRect(float x, float y, float w, float h, const Vec3& color, float alpha) {
    if (!m_initialized) return;

    float verts[24] = {
        x,     y,     0.0f, 0.0f,
        x + w, y,     1.0f, 0.0f,
        x + w, y + h, 1.0f, 1.0f,

        x,     y,     0.0f, 0.0f,
        x + w, y + h, 1.0f, 1.0f,
        x,     y + h, 0.0f, 1.0f
    };

    glUniform3f(m_locColor, color.x, color.y, color.z);
    glUniform1f(m_locAlpha, alpha);
    glUniform1i(m_locUseTexture, 0);

    glBindVertexArray(m_vao);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
    glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(verts), verts);

    glDrawArrays(GL_TRIANGLES, 0, 6);

    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindVertexArray(0);
}

void UIRenderer::drawRectOutline(float x, float y, float w, float h, const Vec3& color, float thickness) {
    drawRect(x, y, w, thickness, color, 1.0f);             // Top
    drawRect(x, y + h - thickness, w, thickness, color, 1.0f); // Bottom
    drawRect(x, y, thickness, h, color, 1.0f);             // Left
    drawRect(x + w - thickness, y, thickness, h, color, 1.0f); // Right
}

void UIRenderer::drawText(const std::string& text, float x, float y, float scale, const Vec3& color, float alpha) {
    if (!m_initialized || text.empty()) return;

    glUniform3f(m_locColor, color.x, color.y, color.z);
    glUniform1f(m_locAlpha, alpha);
    glUniform1i(m_locUseTexture, 1);

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, m_fontTexture);
    glUniform1i(glGetUniformLocation(m_shaderProgram, "uFontTexture"), 0);

    glBindVertexArray(m_vao);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo);

    float curX = x;
    float charW = 8.0f * scale;
    float charH = 16.0f * scale;

    for (char c : text) {
        if (c < 32 || c > 126) c = '?';
        int idx = c - 32;
        int col = idx % 16;
        int row = idx / 16;

        float u0 = col * 8.0f / 128.0f;
        float v0 = row * 16.0f / 128.0f;
        float u1 = (col + 1) * 8.0f / 128.0f;
        float v1 = (row + 1) * 16.0f / 128.0f;

        float verts[24] = {
            curX,         y,         u0, v0,
            curX + charW, y,         u1, v0,
            curX + charW, y + charH, u1, v1,

            curX,         y,         u0, v0,
            curX + charW, y + charH, u1, v1,
            curX,         y + charH, u0, v1
        };

        glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(verts), verts);
        glDrawArrays(GL_TRIANGLES, 0, 6);

        curX += charW;
    }

    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindVertexArray(0);
    glBindTexture(GL_TEXTURE_2D, 0);
}

