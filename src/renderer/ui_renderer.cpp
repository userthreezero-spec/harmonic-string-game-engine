static const char* uiVertexShaderSource = R"(
#version 330 core
layout (location = 0) in vec2 aPos;
layout (location = 1) in vec2 aTexCoord;

uniform mat4 uOrthoProjection;

out vec2 vTexCoord;

void main() {
    vTexCoord = aTexCoord;
    gl_Position = uOrthoProjection * vec4(aPos, 0.0, 1.0);
}
)";

static const char* uiFragmentShaderSource = R"(
#version 330 core
in vec2 vTexCoord;
out vec4 FragColor;

uniform vec3 uColor;
uniform float uAlpha;
uniform int uUseTexture;
uniform sampler2D uFontTexture;

void main() {
    if (uUseTexture == 1) {
        float alpha = texture(uFontTexture, vTexCoord).r;
        if (alpha < 0.1) discard;
        FragColor = vec4(uColor, alpha * uAlpha);
    } else {
        FragColor = vec4(uColor, uAlpha);
    }
}
)";

